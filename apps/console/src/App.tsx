import { useCallback, useEffect, useMemo, useRef, useState } from "react";

import {
  buildWorkGraphModel,
  type ActivityStepSnapshot,
  type ChangeStateSnapshot,
  type EscalationSnapshot,
  type GraphNode,
  type UnitDetailSnapshot,
  type NodeBacking,
  type PlannerDetailSnapshot,
  type JevDetailSnapshot,
  type WorkGraphModel,
} from "@switchyard-change/orchestration/graph-model";

import { GraphView, changeHasPassed } from "./graph-view";
import { TEMPLATES, type Template } from "./templates";

/**
 * Console for the Switchyard Change Fabric: the control plane.
 *
 * After `make dev-all`, a human does everything here in the browser. The console
 * shows a gallery of templates; selecting one launches a real live run with a
 * FRESH UNIQUE Change id (generated by the dev launcher that spawns the run) and
 * the console follows exactly that id. It then polls the Worker's live
 * orchestration state and projects each snapshot into the typed node/edge graph
 * with the shared `buildWorkGraphModel` (the exact same projection the tests
 * pin), and renders it. The morphing a watcher sees (nodes appearing as units
 * become runnable and agents are recruited, greening as evidence lands) is a
 * projection of real state transitions between successive snapshots, never a
 * timed animation.
 *
 * Honesty: because the view is `buildWorkGraphModel(state)` and every node in
 * that model carries a backing that resolves against the state (the builder
 * routes every node through `assertBacked`), it is impossible to show a node
 * with no backing state. Clicking a node reveals its real backing: for an agent
 * node, its real Artifact repo identity and its real status/evidence; for a
 * plain work node, the real WorkUnit it stands for.
 *
 * The escalating template genuinely PAUSES on a real pending escalation: the run
 * blocks until a human answers the question here, and the answer is this
 * console's POST straight to the Worker's resolve route, which ends the durable
 * wait and lets the graph advance. The non-escalating templates run to
 * completion with no human step.
 */

// The Worker control API runs separately under `wrangler dev`. Override with
// VITE_WORKER_URL when it is not on the default local port.
const WORKER_BASE: string =
  (import.meta.env.VITE_WORKER_URL as string | undefined) ?? "http://127.0.0.1:8787";
const POLL_MS = 1200;

/** The launcher-side status of a launched run (from GET /api/runs/:id). */
interface LaunchStatus {
  readonly status: "running" | "exited";
  readonly exitCode: number | null;
  readonly log: readonly string[];
}

export function App() {
  // No change-id box and no ?change= reliance: the console follows the UNIQUE id
  // the launcher hands back when a template is launched. Null means no run yet.
  const [changeId, setChangeId] = useState<string | null>(null);
  const [activeTemplate, setActiveTemplate] = useState<Template | null>(null);
  const [templates, setTemplates] = useState<readonly Template[]>(TEMPLATES);
  const [snapshot, setSnapshot] = useState<ChangeStateSnapshot | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [min, setMin] = useState(1);
  const [max, setMax] = useState(3);
  const [busy, setBusy] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);
  const [launchStatus, setLaunchStatus] = useState<LaunchStatus | null>(null);
  // Per-app live deployment URLs from a MANUAL Deploy (app name -> workers.dev
  // URL). A deployment is created only by a human Deploy, surfaced persistently
  // here from the moment of deploy, through the run (which redeploys the fix in
  // place to the SAME URL), to teardown. This is the pre-run break the watcher
  // sees before launching a fix.
  const [deployedUrls, setDeployedUrls] = useState<Record<string, string>>({});

  // Load the gallery from the launcher so the UI and the launcher share one
  // source of truth; fall back to the bundled descriptors when the launcher is
  // not reachable (for example a static preview build without the dev server).
  useEffect(() => {
    let cancelled = false;
    void fetch("/api/templates")
      .then((res) => (res.ok ? res.json() : null))
      .then((body: { templates?: Template[] } | null) => {
        if (!cancelled && body?.templates && body.templates.length > 0) {
          setTemplates(body.templates);
        }
      })
      .catch(() => {
        /* keep the bundled fallback */
      });
    return () => {
      cancelled = true;
    };
  }, []);

  const load = useCallback(async (id: string) => {
    try {
      const res = await fetch(`${WORKER_BASE}/changes/${encodeURIComponent(id)}`);
      if (!res.ok) {
        // Before the launched run has created the Change, a 404 is expected; show
        // it as a soft "waiting" rather than a hard error so the first paint
        // after a launch is not alarming.
        if (res.status === 404) {
          setError(null);
          return;
        }
        const body = (await res.json().catch(() => ({}))) as { error?: string };
        setError(body.error ?? `request failed (${res.status})`);
        setSnapshot(null);
        return;
      }
      setSnapshot((await res.json()) as ChangeStateSnapshot);
      setError(null);
    } catch {
      setError(`cannot reach the Worker at ${WORKER_BASE}`);
      setSnapshot(null);
    }
  }, []);

  // Poll the Worker for the followed Change id. No run yet means nothing to poll.
  useEffect(() => {
    if (!changeId) {
      return;
    }
    void load(changeId);
    const timer = setInterval(() => void load(changeId), POLL_MS);
    return () => clearInterval(timer);
  }, [changeId, load]);

  // Poll the launcher for the run's process status, so the UI can show when the
  // run is still working, finished, or exited non-zero (an honest status, not a
  // guess from the graph alone).
  useEffect(() => {
    if (!changeId) {
      return;
    }
    let cancelled = false;
    const pull = () => {
      void fetch(`/api/runs/${encodeURIComponent(changeId)}`)
        .then((res) => (res.ok ? res.json() : null))
        .then((body: LaunchStatus | null) => {
          if (!cancelled && body) {
            setLaunchStatus(body);
          }
        })
        .catch(() => {
          /* launcher status is best-effort */
        });
    };
    pull();
    const timer = setInterval(pull, POLL_MS);
    return () => {
      cancelled = true;
      clearInterval(timer);
    };
  }, [changeId]);

  // Build the graph model from the live snapshot. If the snapshot ever fails the
  // backing guard (an unbacked node), surface it loudly rather than drawing a
  // dishonest graph: the no-unbacked-node rule is enforced here too, at render.
  const { model, backingError } = useMemo((): {
    model: WorkGraphModel | null;
    backingError: string | null;
  } => {
    if (!snapshot) {
      return { model: null, backingError: null };
    }
    try {
      return { model: buildWorkGraphModel(snapshot), backingError: null };
    } catch (err) {
      return {
        model: null,
        backingError: err instanceof Error ? err.message : String(err),
      };
    }
  }, [snapshot]);

  // Keep the dial inputs in sync with the real dial the state reports, so the
  // control shows the config actually in force (not a local guess).
  const reportedDial = snapshot?.dial;
  const lastDialKey = useRef<string>("");
  useEffect(() => {
    if (!reportedDial) {
      return;
    }
    const key = `${reportedDial.minConcurrency}/${reportedDial.maxConcurrency}`;
    if (key !== lastDialKey.current) {
      lastDialKey.current = key;
      setMin(reportedDial.minConcurrency);
      setMax(reportedDial.maxConcurrency);
    }
  }, [reportedDial]);

  const selectedNode: GraphNode | null = useMemo(() => {
    if (!model || !selectedId) {
      return null;
    }
    return model.nodes.find((n) => n.id === selectedId) ?? null;
  }, [model, selectedId]);

  const post = useCallback(async (path: string, body?: unknown): Promise<boolean> => {
    try {
      const res = await fetch(`${WORKER_BASE}${path}`, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: body === undefined ? undefined : JSON.stringify(body),
      });
      if (!res.ok) {
        const parsed = (await res.json().catch(() => ({}))) as { error?: string };
        setNotice(parsed.error ?? `request failed (${res.status})`);
        return false;
      }
      return true;
    } catch {
      setNotice(`cannot reach the Worker at ${WORKER_BASE}`);
      return false;
    }
  }, []);

  // The dial is set BEFORE a run and locked during it: there is no mid-run
  // re-POST that changes concurrency live. The chosen min/max is captured as the
  // launched run's config (passed through POST /api/launch), and while a run is
  // active the control is read-only, showing the in-force dial reported by state.

  // Launch a template: ask the launcher to start a real live run with a FRESH
  // UNIQUE Change id, then follow exactly that id. The browser is the launcher,
  // so there is no CLI step for the demo.
  const launchTemplate = useCallback(async (template: Template) => {
    setBusy(true);
    setNotice(null);
    try {
      const res = await fetch("/api/launch", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ templateId: template.id, min, max }),
      });
      if (!res.ok) {
        const parsed = (await res.json().catch(() => ({}))) as { error?: string };
        setNotice(parsed.error ?? `could not launch (${res.status})`);
        setBusy(false);
        return;
      }
      const body = (await res.json()) as { changeId: string };
      // Follow the unique id the launcher generated. Reset the view for the run.
      setSnapshot(null);
      setSelectedId(null);
      setLaunchStatus(null);
      setError(null);
      setActiveTemplate(template);
      setChangeId(body.changeId);
      setNotice(
        template.escalates
          ? `launched ${template.name} as ${body.changeId}. It will pause for your decision when it hits the shared path.`
          : `launched ${template.name} as ${body.changeId}. It runs to completion with no human step.`,
      );
    } catch {
      setNotice("cannot reach the launcher. Is `make dev-all` running?");
    }
    setBusy(false);
  }, [min, max]);

  // Manual Deploy (BEFORE a fix): deploy an app template's app in its CURRENT
  // (broken) state to its STABLE workers.dev URL, so the watcher sees the break
  // first. The URL is surfaced persistently and the fix later redeploys in place
  // to the SAME URL. This never launches a run; it is purely the deploy hop.
  const deployApp = useCallback(async (template: Template) => {
    if (!template.app) {
      return;
    }
    setBusy(true);
    setNotice(null);
    try {
      const res = await fetch("/api/deploy-app", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ templateId: template.id, app: template.app }),
      });
      const body = (await res.json().catch(() => ({}))) as { url?: string; error?: string };
      if (res.ok && body.url) {
        setDeployedUrls((prev) => ({ ...prev, [template.app as string]: body.url as string }));
        setNotice(
          `deployed ${template.name} in its current (broken) state to ${body.url}. ` +
            `Open it to see the break, then launch the fix to redeploy in place to the same URL.`,
        );
      } else {
        setNotice(body.error ?? `could not deploy ${template.name} (${res.status}).`);
      }
    } catch {
      setNotice("cannot reach the launcher to deploy. Is `make dev-all` running?");
    }
    setBusy(false);
  }, []);

  // Per-run cleanup: tear down THIS run's real Artifact repos (scoped to its
  // unique id), so clicking through templates repeatedly never leaves billable
  // repos. A new run uses a fresh unique id, so it never collides with a prior
  // run even before cleanup.
  const cleanupRun = useCallback(async () => {
    if (!changeId) {
      return;
    }
    setBusy(true);
    try {
      const teardownApp = activeTemplate?.app;
      const res = await fetch("/api/cleanup", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ changeId, ...(teardownApp ? { app: teardownApp } : {}) }),
      });
      const body = (await res.json().catch(() => ({}))) as {
        ok?: boolean;
        output?: string[];
        error?: string;
      };
      if (res.ok && body.ok) {
        setNotice(`torn down the real repos for ${changeId}.`);
        setSnapshot(null);
        setSelectedId(null);
        setChangeId(null);
        setActiveTemplate(null);
        setLaunchStatus(null);
        if (teardownApp) {
          setDeployedUrls((prev) => {
            const next = { ...prev };
            delete next[teardownApp];
            return next;
          });
        }
      } else {
        setNotice(body.error ?? `cleanup did not complete for ${changeId}.`);
      }
    } catch {
      setNotice("cannot reach the launcher to clean up. Is `make dev-all` running?");
    }
    setBusy(false);
  }, [changeId, activeTemplate]);

  return (
    <main className="app-shell">
      <header className="app-header">
        <h1>Switchyard Change Fabric</h1>
        <p className="tagline">A living work graph, every node backed by real state</p>
      </header>

      <TemplateGallery
        templates={templates}
        activeId={activeTemplate?.id ?? null}
        busy={busy}
        deployedUrls={deployedUrls}
        onLaunch={launchTemplate}
        onDeploy={deployApp}
      />

      <section className="app-panel" aria-label="How this works">
        <p className="muted">
          The flow for an app template: <strong>Deploy</strong> to see it broken
          at a stable URL, then <strong>Launch the fix</strong> and watch the same
          URL become correct (the run redeploys the fix in place, it never creates
          a new URL), then <strong>Tear down</strong> to delete the deployment and
          the run&apos;s repos. A run with no prior Deploy still fixes the code and
          promotes it to Git; it simply shows no live URL.
        </p>
      </section>

      <section className="app-panel" aria-label="Run status">
        {changeId ? (
          <div className="run-status">
            <p className="muted">
              Following live run <code>{changeId}</code>
              {activeTemplate ? ` (${activeTemplate.name})` : ""}
              {launchStatus
                ? launchStatus.status === "running"
                  ? " - the run is working"
                  : launchStatus.exitCode === 0
                    ? " - the run finished"
                    : ` - the run exited (code ${launchStatus.exitCode ?? "?"})`
                : ""}
            </p>
            {activeTemplate ? (
              <dl className="run-header-detail">
                <dt>What this does</dt>
                <dd>{activeTemplate.whatItDoes}</dd>
                <dt>What this run solves</dt>
                <dd>{activeTemplate.problemItSolves}</dd>
              </dl>
            ) : null}
            {(() => {
              const app = activeTemplate?.app;
              const manualUrl = app ? deployedUrls[app] : undefined;
              const liveUrl = snapshot?.deployment?.url ?? manualUrl;
              if (!liveUrl) {
                return null;
              }
              const redeployed = Boolean(snapshot?.deployment?.url);
              return (
                <p className="deploy-proof">
                  {redeployed ? "Live URL (fix redeployed in place): " : "Live URL (deployed before the fix): "}
                  <a href={liveUrl} target="_blank" rel="noreferrer">
                    {liveUrl}
                  </a>{" "}
                  <span className="muted">
                    {redeployed
                      ? "the same URL now serves the fixed app; torn down on Tear down"
                      : "this shows the CURRENT (broken) app; launch the fix to update it in place"}
                  </span>
                </p>
              );
            })()}
            <button
              type="button"
              className="secondary"
              onClick={() => void cleanupRun()}
              disabled={busy}
              title="Delete this run's real Artifact repos and, if the app was deployed, its stable deployed Worker"
            >
              Tear down (repos{activeTemplate?.app ? " + deployed app" : ""})
            </button>
          </div>
        ) : (
          <p className="muted">
            Pick a template above to launch a live run. The run gets a unique id
            this console follows automatically.
          </p>
        )}
        {error ? <p className="error">{error}</p> : null}
        {notice ? <p className="notice">{notice}</p> : null}
      </section>

      {/*
        The concurrency dial is SET BEFORE a run and LOCKED DURING one. Before a
        run (no changeId yet) the sliders are live: the min/max you choose here
        becomes the launched run's config, passed through POST /api/launch so the
        run recruits under exactly this dial from its first wave. Once a run is
        active the control is READ-ONLY: it shows the in-force dial the run was
        launched with (synced from the real reported dial), and there is no
        mid-run re-POST that changes concurrency live. To run with a different
        dial, set it here before launching the next run.
      */}
      <section className="app-panel dial-panel" aria-label="Concurrency dial">
        <h2>Concurrency dial</h2>
        <p className="muted">
          The min/max dial is the real recruitment config: it bounds how many
          agent nodes run at once, by the same engine mechanism.{" "}
          {changeId
            ? "A run is active, so the dial is locked to the config it launched with."
            : "Set the concurrency for the next run, then launch a template above to apply it."}
        </p>
        <div className="dial-row">
          <label htmlFor="dial-min">min</label>
          <input
            id="dial-min"
            type="range"
            min={0}
            max={8}
            value={min}
            disabled={Boolean(changeId)}
            onChange={(event) => setMin(Number(event.target.value))}
          />
          <span className="dial-value">{min}</span>
          <label htmlFor="dial-max">max</label>
          <input
            id="dial-max"
            type="range"
            min={1}
            max={8}
            value={max}
            disabled={Boolean(changeId)}
            onChange={(event) => setMax(Number(event.target.value))}
          />
          <span className="dial-value">{max}</span>
          {changeId ? (
            <span className="dial-locked" title="The dial is fixed for the life of a run">
              locked for this run
            </span>
          ) : null}
        </div>
        {changeId ? (
          reportedDial ? (
            <p className="muted">
              in force for this run: min {reportedDial.minConcurrency}, max{" "}
              {reportedDial.maxConcurrency} (read-only until the run ends)
            </p>
          ) : (
            <p className="muted">
              launched with min {min}, max {max}: this run keeps that dial for its
              lifetime
            </p>
          )
        ) : (
          <p className="muted">
            no run yet: this is the concurrency the next launched run will use
          </p>
        )}
      </section>

      {backingError ? (
        <section className="app-panel" aria-label="Honesty guard">
          <p className="error">
            Refusing to render: a node had no backing state ({backingError}). The graph
            only draws nodes that map to real ChangeState.
          </p>
        </section>
      ) : null}

      {snapshot && changeId && (snapshot.escalations?.length ?? 0) > 0 ? (
        <EscalationPanel
          escalations={snapshot.escalations ?? []}
          busy={busy}
          onResolve={async (id, decision) => {
            setBusy(true);
            const ok = await post(
              `/changes/${encodeURIComponent(changeId)}/escalations/${encodeURIComponent(id)}/resolve`,
              { decision },
            );
            if (ok) {
              setNotice(`escalation ${id} resolved: ${decision}. The run continues.`);
              await load(changeId);
            }
            setBusy(false);
          }}
        />
      ) : null}

      {model ? (
        <section className="app-panel graph-panel" aria-label="Living work graph">
          <GraphView model={model} selectedId={selectedId} onSelect={setSelectedId} />
          <Legend />
        </section>
      ) : null}

      {selectedNode ? (
        <NodeDetail
          node={selectedNode}
          changePassed={model ? changeHasPassed(model) : false}
          onClose={() => setSelectedId(null)}
        />
      ) : null}
    </main>
  );
}

/**
 * The template gallery: the shipped scenarios as selectable cards. Each card
 * declares its display name, a one-line description, an agent count hint, and
 * whether it escalates (pauses for a human) or runs autonomously. Clicking a
 * card launches a real live run with a fresh unique id the console follows.
 */
function TemplateGallery({
  templates,
  activeId,
  busy,
  deployedUrls,
  onLaunch,
  onDeploy,
}: {
  templates: readonly Template[];
  activeId: string | null;
  busy: boolean;
  deployedUrls: Record<string, string>;
  onLaunch: (template: Template) => void | Promise<void>;
  onDeploy: (template: Template) => void | Promise<void>;
}) {
  return (
    <section className="app-panel template-gallery" aria-label="Template gallery">
      <h2>Templates</h2>
      <p className="muted">
        Pick a scenario to launch a live run. The browser is the launcher: there
        is no CLI step. For an app template, Deploy it first to see it broken at a
        stable URL, then launch the fix to update that same URL in place.
      </p>
      <ul className="template-list">
        {templates.map((template) => {
          const deployedUrl = template.app ? deployedUrls[template.app] : undefined;
          return (
            <li
              key={template.id}
              className={`template-card${template.id === activeId ? " active" : ""}`}
            >
              <div className="template-head">
                <h3>{template.name}</h3>
                <span className={`template-badge ${template.escalates ? "escalates" : "autonomous"}`}>
                  {template.escalates ? "pauses for you" : "autonomous"}
                </span>
              </div>
              <p className="template-desc">{template.description}</p>
              <dl className="template-detail">
                <dt>What this does</dt>
                <dd>{template.whatItDoes}</dd>
                <dt>What this run solves</dt>
                <dd>{template.problemItSolves}</dd>
              </dl>
              <p className="muted template-count">{template.agentCountHint}</p>
              {deployedUrl ? (
                <p className="deploy-proof template-deployed">
                  Deployed (current state):{" "}
                  <a href={deployedUrl} target="_blank" rel="noreferrer">
                    {deployedUrl}
                  </a>{" "}
                  <span className="muted">the fix will update this same URL in place</span>
                </p>
              ) : null}
              <div className="template-actions">
                {template.app ? (
                  <button
                    type="button"
                    className="secondary"
                    onClick={() => void onDeploy(template)}
                    disabled={busy}
                    title="Deploy this app in its CURRENT (broken) state to its stable live URL, before any fix"
                  >
                    {deployedUrl ? "Redeploy current state" : "Deploy app (see it broken)"}
                  </button>
                ) : null}
                <button type="button" onClick={() => void onLaunch(template)} disabled={busy}>
                  Launch {template.name}
                </button>
              </div>
            </li>
          );
        })}
      </ul>
    </section>
  );
}

/** The legend explaining node and edge kinds, matching graph-view exactly. */
function Legend() {
  return (
    <ul className="legend" aria-label="Legend">
      {/* The node kinds, matching the shapes graph-view draws. Node COLOR still
          conveys status in the graph (a failed agent circle red, a verify
          hexagon green/red), but the legend lists only the kinds, never a status
          swatch. */}
      {/* The goal is a DIAMOND. */}
      <li><span className="swatch-diamond sw-goal" aria-hidden="true" /> goal</li>
      {/* The planner is a TRIANGLE (the schema-constrained decomposer). */}
      <li><span className="swatch-triangle sw-planner" aria-hidden="true" /> planner</li>
      {/* An agent is a CIRCLE. */}
      <li><span className="swatch sw-agent" /> agent</li>
      {/* A verify node is a HEXAGON (a mechanical gate run). */}
      <li><span className="swatch-hex sw-verify" aria-hidden="true" /> verify</li>
      {/* A retry node is the SAME hexagon shape in a different color (the
          smarter-model re-attempt). */}
      <li><span className="swatch-hex sw-retry" aria-hidden="true" /> retry</li>
      {/* A jev node is a PENTAGON (a typed-decision beat at a juncture). */}
      <li><span className="swatch-pentagon sw-jev" aria-hidden="true" /> jev</li>
      {/* A tool is a YELLOW SQUARE. */}
      <li><span className="swatch-square sw-tool" aria-hidden="true" /> tool</li>
      {/* The rendered edge vocabulary is exactly these three kinds. */}
      <li><span className="line ln-dependency" /> dependency</li>
      <li><span className="line ln-spawn" /> event-driven spawn</li>
      <li><span className="line ln-tool" /> consumed tool</li>
    </ul>
  );
}

/**
 * The escalation panel: the pending human decisions the engine is waiting on,
 * plus the resolved ones for context. A pending escalation is a durable wait in
 * ChangeState (the engine does not self-certify past it); resolving one here
 * POSTs the human decision to the Worker, which ends the wait and lets the
 * graph advance. Each pending escalation also lights its node red in the graph.
 */
function EscalationPanel({
  escalations,
  busy,
  onResolve,
}: {
  escalations: readonly EscalationSnapshot[];
  busy: boolean;
  onResolve: (id: string, decision: string) => void | Promise<void>;
}) {
  const pending = escalations.filter((e) => e.status === "pending");
  const resolved = escalations.filter((e) => e.status === "resolved");
  return (
    <section className="app-panel escalation-panel" aria-label="Human escalations">
      <h2>Human escalations</h2>
      <p className="muted">
        A fork mechanical evidence cannot settle. The engine recorded it and is
        waiting on a human decision; it does not self-certify past it.
      </p>
      {pending.length === 0 ? (
        <p className="muted">No pending escalation.</p>
      ) : (
        <ul className="escalation-list">
          {pending.map((escalation) => (
            <li key={escalation.id} className="escalation pending">
              <p className="escalation-question">{escalation.question}</p>
              <p className="muted">
                {escalation.kind}
                {escalation.unitId ? ` on ${escalation.unitId}` : ""}
                {escalation.path ? ` (${escalation.path})` : ""}
              </p>
              <div className="escalation-options">
                {(escalation.options ?? []).length > 0 ? (
                  (escalation.options ?? []).map((option) => (
                    <button
                      key={option}
                      type="button"
                      disabled={busy}
                      onClick={() => void onResolve(escalation.id, option)}
                    >
                      {option}
                    </button>
                  ))
                ) : (
                  <button
                    type="button"
                    disabled={busy}
                    onClick={() => void onResolve(escalation.id, "proceed")}
                  >
                    Resolve
                  </button>
                )}
              </div>
            </li>
          ))}
        </ul>
      )}
      {resolved.length > 0 ? (
        <details className="escalation-resolved">
          <summary>{resolved.length} resolved</summary>
          <ul>
            {resolved.map((escalation) => (
              <li key={escalation.id} className="muted">
                {escalation.question} -&gt; <strong>{escalation.decision}</strong>
              </li>
            ))}
          </ul>
        </details>
      ) : null}
    </section>
  );
}

/**
 * The node detail panel: the real backing of the clicked node, with two tiers of
 * per-node feedback, both read from real state:
 *
 *   1. MODEL TRANSCRIPT: the agent's real prompt summary, the model's proposed
 *      edit (changed paths + a readable diff), the proposed commit message, the
 *      model id, and tokens/cost, read from the unit's recorded `detail` in
 *      state (never synthesized). This static transcript is posted when a unit
 *      is done, so there is no live token stream to render.
 *   2. PER-NODE ACTIVITY LOG: the ordered real run steps the runner reported
 *      (leased, cloning, calling model, applying edit, committing, pushing,
 *      verified/failed), read from the unit's recorded `activity` in state.
 *
 * The Artifact repo identity and the raw backing remain, so nothing here is
 * synthesized: every field is read straight from the node's backing or the
 * unit's recorded steps/detail, which were validated against the state.
 */
export function NodeDetail({
  node,
  changePassed = false,
  onClose,
}: {
  node: GraphNode;
  changePassed?: boolean;
  onClose: () => void;
}) {
  const backing = node.backing;
  const detail = node.detail;
  const activity = node.activity ?? [];
  // The unit id this node stands for (work/agent nodes carry it in the backing).
  const unitId =
    backing.kind === "work-unit" || backing.kind === "workspace" ? backing.unitId : null;

  return (
    <section className="app-panel detail-panel" aria-label="Node detail">
      <div className="detail-head">
        <h2>
          {node.label} <span className="muted">[{node.kind}]</span>
        </h2>
        <button type="button" className="secondary" onClick={onClose}>
          Close
        </button>
      </div>

      <dl className="meta">
        <div>
          <dt>Status</dt>
          <dd>{node.status}</dd>
        </div>
        <div>
          <dt>Verified</dt>
          <dd>{node.verified ? "yes" : "no"}</dd>
        </div>
        <div>
          <dt>Backing kind</dt>
          <dd>{backing.kind}</dd>
        </div>
      </dl>

      {backing.kind === "round-agent" && node.status === "failed" && changePassed ? (
        <p className="detail-note muted">
          This retry agent failed its own attempt, but the change still passed its
          authoritative gate. It is a per-attempt retry failure that did not block
          the change (an earlier edit sufficed, or this re-fan produced no change),
          not a failure of the overall change.
        </p>
      ) : null}

      {detail ? <ModelDetail detail={detail} /> : null}

      {node.kind === "planner" && node.plannerDetail ? (
        <PlannerDetail detail={node.plannerDetail} />
      ) : null}

      {node.kind === "jev" && node.jevDetail ? (
        <JevDetail detail={node.jevDetail} />
      ) : null}

      {backing.kind === "verify-attempt" || backing.kind === "retry-attempt" ? (
        <LadderDetail backing={backing} />
      ) : null}

      {unitId ? (
        <ActivityLog steps={activity} />
      ) : null}

      {node.workspace ? (
        <>
          <h3>Real Artifact repo backing</h3>
          <dl className="meta">
            <div>
              <dt>Repo name</dt>
              <dd><code>{node.workspace.workspaceName}</code></dd>
            </div>
            <div>
              <dt>Clone URL</dt>
              <dd><code>{node.workspace.gitUrl}</code></dd>
            </div>
            <div>
              <dt>Branch</dt>
              <dd><code>{node.workspace.defaultBranch}</code></dd>
            </div>
            <div>
              <dt>Backend</dt>
              <dd>
                {node.workspace.backend}
                {node.workspace.fallback ? " (honest local/offline fallback)" : " (live)"}
              </dd>
            </div>
            {node.workspace.leasedAt ? (
              <div>
                <dt>Leased at</dt>
                <dd>{node.workspace.leasedAt}</dd>
              </div>
            ) : null}
          </dl>
        </>
      ) : (
        <p className="muted">
          No agent has been recruited for this unit yet, so it has no Artifact repo.
          It becomes an agent node (with a real repo) once the engine recruits it.
        </p>
      )}

      <details className="raw-backing">
        <summary>Raw backing state</summary>
        <pre>{JSON.stringify(node.backing, null, 2)}</pre>
      </details>
    </section>
  );
}

/**
 * The static model transcript: the agent's real prompt summary, the model id,
 * token usage and cost, the proposed edit (changed paths + a readable diff), and
 * the proposed commit message. Every field comes from the unit's recorded
 * `detail` in state; absent fields are simply not shown, so this reflects exactly
 * what the run produced. It is a static read of real state posted when the unit
 * is done, not a live token stream.
 */
function ModelDetail({ detail }: { detail: UnitDetailSnapshot }) {
  const hasTokens =
    detail.inputTokens !== undefined ||
    detail.outputTokens !== undefined ||
    detail.usd !== undefined;
  return (
    <div className="model-detail">
      <h3>Model transcript</h3>
      {detail.model ? (
        <p className="muted">
          model <code>{detail.model}</code>
        </p>
      ) : null}
      {hasTokens ? (
        <dl className="meta">
          {detail.inputTokens !== undefined ? (
            <div>
              <dt>Input tokens</dt>
              <dd>{detail.inputTokens}</dd>
            </div>
          ) : null}
          {detail.outputTokens !== undefined ? (
            <div>
              <dt>Output tokens</dt>
              <dd>{detail.outputTokens}</dd>
            </div>
          ) : null}
          {detail.usd !== undefined ? (
            <div>
              <dt>Cost (USD)</dt>
              <dd>{detail.usd}</dd>
            </div>
          ) : null}
        </dl>
      ) : null}
      {detail.promptSummary ? (
        <>
          <h4>Prompt</h4>
          <pre className="detail-pre">{detail.promptSummary}</pre>
        </>
      ) : null}
      {detail.commitMessage ? (
        <p className="muted">
          proposed commit: <strong>{detail.commitMessage}</strong>
        </p>
      ) : null}
      {detail.editedPaths && detail.editedPaths.length > 0 ? (
        <>
          <h4>Proposed edit ({detail.editedPaths.length} file(s))</h4>
          <ul className="paths">
            {detail.editedPaths.map((p) => (
              <li key={p}>
                <code>{p}</code>
              </li>
            ))}
          </ul>
        </>
      ) : null}
      {detail.diff ? (
        <>
          <h4>Diff</h4>
          <pre className="detail-diff">{detail.diff}</pre>
        </>
      ) : null}
    </div>
  );
}

/**
 * The planner detail panel: the real recorded plan the PLANNER node produced,
 * read straight from the node's plannerDetail (derived from the recorded plan,
 * never synthesized). It is the planner's parallel of the agent ModelDetail, in
 * the same styling family:
 *
 *   - SOURCE: whether the inference planner decided the decomposition, or the
 *     deterministic heuristic fallback did (when no model returned a usable
 *     plan). This is the honest provenance of the plan.
 *   - MODEL: the model that produced an accepted plan (empty on the fallback).
 *   - PROMPT SUMMARY: a readable, secret-free summary of what the planner was
 *     asked (the goal plus the structural module map it was handed).
 *   - RATIONALE: the model's short explanation of why this decomposition, when
 *     it supplied one.
 *   - THE PLAN: the planned units with their objectives, the agent count the
 *     plan chose (one agent per unit), and the frozen read-only contracts the
 *     plan froze (owned by no unit).
 *
 * Every field comes from the recorded plan, so the panel can only show a plan
 * that genuinely drove the Change.
 */
function PlannerDetail({ detail }: { detail: PlannerDetailSnapshot }) {
  const isPlanner = detail.source === "planner";
  return (
    <div className="model-detail planner-detail">
      <h3>Plan</h3>
      <dl className="meta">
        <div>
          <dt>Source</dt>
          <dd>{isPlanner ? "inference planner" : "heuristic fallback"}</dd>
        </div>
        <div>
          <dt>Model</dt>
          <dd>{detail.model ? <code>{detail.model}</code> : <span className="muted">none (heuristic)</span>}</dd>
        </div>
        <div>
          <dt>Agents</dt>
          <dd>{detail.agentCount}</dd>
        </div>
      </dl>
      <p className="muted">
        {isPlanner
          ? "The schema-constrained planner decided the in-scope modules, each unit objective, the agent count, and the dependency order within the real structure."
          : "No model returned a usable plan, so the deterministic heuristic decomposed the goal. The plan is honest about being the fallback."}
      </p>
      {detail.promptSummary ? (
        <>
          <h4>Prompt summary</h4>
          <pre className="detail-pre">{detail.promptSummary}</pre>
        </>
      ) : null}
      {detail.rationale ? (
        <>
          <h4>Rationale</h4>
          <pre className="detail-pre">{detail.rationale}</pre>
        </>
      ) : null}
      <h4>Planned units ({detail.units.length})</h4>
      {detail.units.length === 0 ? (
        <p className="muted">The plan recorded no units.</p>
      ) : (
        <ul className="planner-units">
          {detail.units.map((unit) => (
            <li key={unit.id}>
              <code>{unit.id}</code>
              {unit.objective ? <span className="planner-objective"> {unit.objective}</span> : null}
            </li>
          ))}
        </ul>
      )}
      <h4>Frozen contracts ({detail.contracts.length})</h4>
      {detail.contracts.length === 0 ? (
        <p className="muted">The plan froze no read-only contracts.</p>
      ) : (
        <ul className="paths">
          {detail.contracts.map((path) => (
            <li key={path}>
              <code>{path}</code>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

/**
 * The Jev decision detail panel: the real recorded typed decision the `jev` node
 * stands for, read straight from the node's jevDetail (derived from the recorded
 * decision, never synthesized). It shows:
 *
 *   - JUNCTURE: plan-review ("does this plan cover the goal?"), attribution
 *     ("which module(s) does this failure implicate?"), or fix-confidence ("is
 *     this fix acceptable?"). A fix-confidence decision is advisory ONLY: it is a
 *     recorded confidence signal and never changed the authoritative mechanical
 *     gate verdict or the promote/deploy decision.
 *   - QUESTION: the exact question the decision model answered.
 *   - TYPED ANSWER: the noul verdict, the chosen option, or the score, by kind.
 *   - CALIBRATED CONFIDENCE: the model's confidence in [0, 1], and any per
 *     outcome probabilities it returned.
 *   - ACCEPTED or ESCALATED: whether the engine confidently used the answer, or
 *     escalated because it was low-confidence or a confident "no".
 *
 * Every field comes from the recorded decision, so the panel can only show a
 * decision that genuinely happened.
 */
function JevDetail({ detail }: { detail: JevDetailSnapshot }) {
  const answer =
    detail.answerType === "noul"
      ? (detail.noul ?? "unsure")
      : detail.answerType === "choice"
        ? (detail.choice ?? "(none)")
        : String(detail.score ?? "");
  const probabilities = detail.probabilities
    ? Object.entries(detail.probabilities)
    : [];
  const juncture =
    detail.juncture === "plan-review"
      ? "plan review (does this plan cover the goal?)"
      : detail.juncture === "attribution"
        ? "failure attribution (which module(s) does this implicate?)"
        : "fix confidence (is this fix acceptable?) - advisory only";
  return (
    <div className="model-detail jev-detail">
      <h3>Typed decision</h3>
      <dl className="meta">
        <div>
          <dt>Juncture</dt>
          <dd>{juncture}</dd>
        </div>
        <div>
          <dt>Answer</dt>
          <dd>
            <code>{answer}</code> <span className="muted">({detail.answerType})</span>
          </dd>
        </div>
        <div>
          <dt>Confidence</dt>
          <dd>{detail.confidence.toFixed(2)}</dd>
        </div>
        <div>
          <dt>Outcome</dt>
          <dd className={detail.accepted ? "verdict-pass" : "verdict-fail"}>
            {detail.accepted ? "accepted (confident)" : "escalated (unsure)"}
          </dd>
        </div>
      </dl>
      <h4>Question</h4>
      <pre className="detail-pre">{detail.question}</pre>
      {detail.juncture === "fix-confidence" ? (
        <p className="muted">
          This is a secondary advisory signal. The mechanical gate verdict is
          authoritative and decides promotion and deploy; this never flips it.
        </p>
      ) : null}
      {probabilities.length > 0 ? (
        <>
          <h4>Calibrated probabilities</h4>
          <dl className="meta">
            {probabilities.map(([key, value]) => (
              <div key={key}>
                <dt>{key}</dt>
                <dd>{Number(value).toFixed(2)}</dd>
              </div>
            ))}
          </dl>
        </>
      ) : null}
    </div>
  );
}

/**
 * The per-node detail for the CHANGE-LEVEL model-escalation ladder's own nodes,
 * read straight from the node's real backing (never synthesized):
 *
 *   - a VERIFY node shows the round, the mechanical verdict (pass or fail) of
 *     that single whole-change gate run, the gate command that ran, and, on a
 *     fail, the real failing gate output. The verdict is ground truth: the gate
 *     is mechanical on every round, so the model never grades its own output.
 *   - a RETRY node shows the round, the escalation reason, the implicated unit
 *     ids it re-fanned, and the base -> escalation model hop. This is the
 *     smarter-model re-attempt beat, wholly separate from any human escalation.
 *
 * Both come from the backing variant the graph model attached, so this panel can
 * only show a ladder beat that genuinely happened.
 */
/**
 * A readable label for a re-fan source (how the implicated units were chosen):
 * the string-parse of the failing gate output, a confident Jev attribution
 * choice, a configured re-plan, or the honest re-fan-all fallback.
 */
function refanSourceLabel(source: "parse" | "jev" | "re-plan" | "all"): string {
  switch (source) {
    case "parse":
      return "gate-output parse";
    case "jev":
      return "Jev attribution";
    case "re-plan":
      return "re-plan";
    case "all":
      return "re-fan all (unattributable)";
  }
}

/** A short explainer of what the re-fan source values mean. */
const refanSourceExplainer =
  "a parse of the failing gate output, a confident Jev attribution choice, a configured re-plan, or the honest re-fan-all fallback when the failure could not be attributed";

function LadderDetail({
  backing,
}: {
  backing: Extract<NodeBacking, { kind: "verify-attempt" | "retry-attempt" }>;
}) {
  if (backing.kind === "verify-attempt") {
    return (
      <div className="ladder-detail">
        <h3>Verify round</h3>
        <dl className="meta">
          <div>
            <dt>Round</dt>
            <dd>#{backing.round}</dd>
          </div>
          <div>
            <dt>Verdict</dt>
            <dd className={backing.outcome === "pass" ? "verdict-pass" : "verdict-fail"}>
              {backing.outcome === "pass" ? "pass" : "fail"}
            </dd>
          </div>
          {backing.gateCommand ? (
            <div>
              <dt>Gate command</dt>
              <dd>
                <code>{backing.gateCommand}</code>
              </dd>
            </div>
          ) : null}
        </dl>
        <p className="muted">
          The per-app gate ran ONCE against the whole integrated change for this
          round. The verdict is real evidence, not the model grading itself.
        </p>
        {backing.outcome === "fail" && backing.failingOutput ? (
          <>
            <h4>Failing gate output</h4>
            <pre className="detail-pre">{backing.failingOutput}</pre>
          </>
        ) : null}
        {backing.outcome === "fail" &&
        backing.implicatedUnits &&
        backing.implicatedUnits.length > 0 ? (
          <>
            <h4>
              Re-fanned units ({backing.implicatedUnits.length})
              {backing.refanSource ? ` via ${refanSourceLabel(backing.refanSource)}` : ""}
            </h4>
            <ul className="paths">
              {backing.implicatedUnits.map((u) => (
                <li key={u}>
                  <code>{u}</code>
                </li>
              ))}
            </ul>
            <p className="muted">
              This round's failure re-fanned these units on the next round. The
              re-fan source shows how they were chosen: {refanSourceExplainer}.
            </p>
          </>
        ) : null}
      </div>
    );
  }
  return (
    <div className="ladder-detail">
      <h3>Model escalation retry</h3>
      <dl className="meta">
        <div>
          <dt>Round</dt>
          <dd>#{backing.round}</dd>
        </div>
        <div>
          <dt>Model hop</dt>
          <dd>
            <code>{backing.fromModel || "base"}</code> {"->"}{" "}
            <code>{backing.toModel || "escalation model"}</code>
          </dd>
        </div>
      </dl>
      {backing.reason ? <p className="muted">{backing.reason}</p> : null}
      {backing.refanSource ? (
        <p className="muted">
          Re-fan source: <strong>{refanSourceLabel(backing.refanSource)}</strong>.
        </p>
      ) : null}
      <h4>Implicated units ({backing.implicatedUnits.length})</h4>
      {backing.implicatedUnits.length === 0 ? (
        <p className="muted">No specific unit was recorded for this retry.</p>
      ) : (
        <ul className="paths">
          {backing.implicatedUnits.map((u) => (
            <li key={u}>
              <code>{u}</code>
            </li>
          ))}
        </ul>
      )}
      <p className="muted">
        A change-level verify-fail re-fanned the implicated units on a stronger
        model, fed the failing evidence. This is a distinct beat from a human
        escalation.
      </p>
    </div>
  );
}

/**
 * The per-node activity log: the ordered REAL run steps the runner reported for
 * this unit (leased, cloning, calling model, applying edit, committing, pushing,
 * verified/failed). It renders the unit's recorded `activity` from state, so
 * every line corresponds to a real step the run emitted, not a UI-synthesized
 * one. An empty log means the run has not reported any step for this unit yet.
 */
function ActivityLog({ steps }: { steps: readonly ActivityStepSnapshot[] }) {
  return (
    <div className="activity-log">
      <h3>Activity log</h3>
      {steps.length === 0 ? (
        <p className="muted">No activity reported for this unit yet.</p>
      ) : (
        <ol className="activity-steps">
          {steps.map((step, i) => (
            <li key={`${step.at}-${i}`} className={`activity-step phase-${step.phase}`}>
              <span className="activity-phase">{step.phase}</span>
              <span className="activity-message">{step.message}</span>
            </li>
          ))}
        </ol>
      )}
    </div>
  );
}
