/**
 * The static model transcript: the agent's real prompt summary, the model id,
 * token usage and cost, the proposed edit (changed paths + a readable diff), and
 * the proposed commit message. Every field comes from the unit's recorded
 * `detail` in state; absent fields are simply not shown, so this reflects exactly
 * what the run produced. It is a static read of real state posted when the unit
 * is done, not a live token stream.
 */
function ModelDetail({ detail }: { detail: UnitDetailSnapshot }) {
  const cost = formatCost(detail);
  const hasTokens =
    detail.inputTokens !== undefined || detail.outputTokens !== undefined || cost !== null;
  return (
    <div className="model-detail">
      <h3>Model transcript</h3>
      {detail.model ? (
        <p className="muted">
          model <code>{detail.model}</code>
        </p>
      ) : null}
      {hasTokens ? (
        <dl className="meta">
          {detail.inputTokens !== undefined ? (
            <div>
              <dt>Input tokens</dt>
              <dd>{detail.inputTokens}</dd>
            </div>
          ) : null}
          {detail.outputTokens !== undefined ? (
            <div>
              <dt>Output tokens</dt>
              <dd>{detail.outputTokens}</dd>
            </div>
          ) : null}
          {cost !== null ? (
            <div>
              <dt>Cost (USD)</dt>
              <dd>{cost}</dd>
            </div>
          ) : null}
        </dl>
      ) : null}
      {detail.promptSummary ? (
        <>
          <h4>Prompt</h4>
          <pre className="detail-pre">{detail.promptSummary}</pre>
        </>
      ) : null}
      {detail.commitMessage ? (
        <p className="muted">
          proposed commit: <strong>{detail.commitMessage}</strong>
        </p>
      ) : null}
      {detail.editedPaths && detail.editedPaths.length > 0 ? (
        <>
          <h4>Proposed edit ({detail.editedPaths.length} file(s))</h4>
          <ul className="paths">
            {detail.editedPaths.map((p) => (
              <li key={p}>
                <code>{p}</code>
              </li>
            ))}
          </ul>
        </>
      ) : null}
      {detail.diff ? (
        <>
          <h4>Diff</h4>
          <pre className="detail-diff">{detail.diff}</pre>
        </>
      ) : null}
    </div>
  );
}

/**
 * The planner detail panel: the real recorded plan the PLANNER node produced,
 * read straight from the node's plannerDetail (derived from the recorded plan,
 * never synthesized). It is the planner's parallel of the agent ModelDetail, in
 * the same styling family:
 *
 *   - SOURCE: whether the inference planner decided the decomposition, or the
 *     deterministic heuristic fallback did (when no model returned a usable
 *     plan). This is the honest provenance of the plan.
 *   - MODEL: the model that produced an accepted plan (empty on the fallback).
 *   - PROMPT SUMMARY: a readable, secret-free summary of what the planner was
 *     asked (the goal plus the structural module map it was handed).
 *   - RATIONALE: the model's short explanation of why this decomposition, when
 *     it supplied one.
 *   - THE PLAN: the planned units with their objectives, the agent count the
 *     plan chose (one agent per unit), and the frozen read-only contracts the
 *     plan froze (owned by no unit).
 *
 * Every field comes from the recorded plan, so the panel can only show a plan
 * that genuinely drove the Change.
 */
function PlannerDetail({ detail }: { detail: PlannerDetailSnapshot }) {
  const isPlanner = detail.source === "planner";
  return (
    <div className="model-detail planner-detail">
      <h3>Plan</h3>
      <dl className="meta">
        <div>
          <dt>Source</dt>
          <dd>{isPlanner ? "inference planner" : "heuristic fallback"}</dd>
        </div>
        <div>
          <dt>Model</dt>
          <dd>{detail.model ? <code>{detail.model}</code> : <span className="muted">none (heuristic)</span>}</dd>
        </div>
        <div>
          <dt>Agents</dt>
          <dd>{detail.agentCount}</dd>
        </div>
      </dl>
      <p className="muted">
        {isPlanner
          ? "The schema-constrained planner decided the in-scope modules, each unit objective, the agent count, and the dependency order within the real structure."
          : "No model returned a usable plan, so the deterministic heuristic decomposed the goal. The plan is honest about being the fallback."}
      </p>
      {detail.promptSummary ? (
        <>
          <h4>Prompt summary</h4>
          <pre className="detail-pre">{detail.promptSummary}</pre>
        </>
      ) : null}
      {detail.rationale ? (
        <>
          <h4>Rationale</h4>
          <pre className="detail-pre">{detail.rationale}</pre>
        </>
      ) : null}
      <h4>Planned units ({detail.units.length})</h4>
      {detail.units.length === 0 ? (
        <p className="muted">The plan recorded no units.</p>
      ) : (
        <ul className="planner-units">
          {detail.units.map((unit) => (
            <li key={unit.id}>
              <code>{unit.id}</code>
              {unit.objective ? <span className="planner-objective"> {unit.objective}</span> : null}
            </li>
          ))}
        </ul>
      )}
      <h4>Frozen contracts ({detail.contracts.length})</h4>
      {detail.contracts.length === 0 ? (
        <p className="muted">The plan froze no read-only contracts.</p>
      ) : (
        <ul className="paths">
          {detail.contracts.map((path) => (
            <li key={path}>
              <code>{path}</code>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

/**
 * The Jev decision detail panel: the real recorded typed decision the `jev` node
 * stands for, read straight from the node's jevDetail (derived from the recorded
 * decision, never synthesized). It shows:
 *
 *   - JUNCTURE: plan-review ("does this plan cover the goal?"), attribution
 *     ("which module(s) does this failure implicate?"), or fix-confidence ("is
 *     this fix acceptable?"). A fix-confidence decision is advisory ONLY: it is a
 *     recorded confidence signal and never changed the authoritative mechanical
 *     gate verdict or the promote/deploy decision.
 *   - QUESTION: the exact question the decision model answered.
 *   - TYPED ANSWER: the noul verdict, the chosen option, or the score, by kind.
 *   - CALIBRATED CONFIDENCE: the model's confidence in [0, 1], and any per
 *     outcome probabilities it returned.
 *   - ACCEPTED or ESCALATED: whether the engine confidently used the answer, or
 *     escalated because it was low-confidence or a confident "no".
 *
 * Every field comes from the recorded decision, so the panel can only show a
 * decision that genuinely happened.
 */
function JevDetail({ detail }: { detail: JevDetailSnapshot }) {
  const answer =
    detail.answerType === "noul"
      ? (detail.noul ?? "unsure")
      : detail.answerType === "choice"
        ? (detail.choice ?? "(none)")
        : String(detail.score ?? "");
  const probabilities = detail.probabilities
    ? Object.entries(detail.probabilities)
    : [];
  const juncture =
    detail.juncture === "plan-review"
      ? "plan review (does this plan cover the goal?)"
      : detail.juncture === "attribution"
        ? "failure attribution (which module(s) does this implicate?)"
        : "fix confidence (is this fix acceptable?) - advisory only";
  return (
    <div className="model-detail jev-detail">
      <h3>Typed decision</h3>
      <dl className="meta">
        <div>
          <dt>Juncture</dt>
          <dd>{juncture}</dd>
        </div>
        <div>
          <dt>Answer</dt>
          <dd>
            <code>{answer}</code> <span className="muted">({detail.answerType})</span>
          </dd>
        </div>
        <div>
          <dt>Confidence</dt>
          <dd>{detail.confidence.toFixed(2)}</dd>
        </div>
        <div>
          <dt>Outcome</dt>
          <dd className={detail.accepted ? "verdict-pass" : "verdict-fail"}>
            {detail.accepted ? "accepted (confident)" : "escalated (unsure)"}
          </dd>
        </div>
      </dl>
      <h4>Question</h4>
      <pre className="detail-pre">{detail.question}</pre>
      {detail.juncture === "fix-confidence" ? (
        <p className="muted">
          This is a secondary advisory signal. The mechanical gate verdict is
          authoritative and decides promotion and deploy; this never flips it.
        </p>
      ) : null}
      {probabilities.length > 0 ? (
        <>
          <h4>Calibrated probabilities</h4>
          <dl className="meta">
            {probabilities.map(([key, value]) => (
              <div key={key}>
                <dt>{key}</dt>
                <dd>{Number(value).toFixed(2)}</dd>
              </div>
            ))}
          </dl>
        </>
      ) : null}
    </div>
  );
}

/**
 * The per-node detail for the CHANGE-LEVEL model-escalation ladder's own nodes,
 * read straight from the node's real backing (never synthesized):
 *
 *   - a VERIFY node shows the round, the mechanical verdict (pass or fail) of
 *     that single whole-change gate run, the gate command that ran, and, on a
 *     fail, the real failing gate output. The verdict is ground truth: the gate
 *     is mechanical on every round, so the model never grades its own output.
 *   - a RETRY node shows the round, the escalation reason, the implicated unit
 *     ids it re-fanned, and the base -> escalation model hop. This is the
 *     smarter-model re-attempt beat, wholly separate from any human escalation.
 *
 * Both come from the backing variant the graph model attached, so this panel can
 * only show a ladder beat that genuinely happened.
 */
/**
 * A readable label for a re-fan source (how the implicated units were chosen):
 * the string-parse of the failing gate output, a confident Jev attribution
 * choice, the LLM planner's re-plan, or the honest re-fan-all fallback.
 */
function refanSourceLabel(source: "parse" | "jev" | "re-plan" | "all"): string {
  switch (source) {
    case "parse":
      return "gate-output parse";
    case "jev":
      return "Jev attribution";
    case "re-plan":
      return "re-plan";
    case "all":
      return "re-fan all (unattributable)";
  }
}

/** A short explainer of what the re-fan source values mean. */
const refanSourceExplainer =
  "a parse of the failing gate output, a confident Jev attribution, the LLM planner re-planning (it re-plans on every failing round), or re-fan-all when the failure could not be attributed";

function LadderDetail({
  backing,
}: {
  backing: Extract<NodeBacking, { kind: "verify-attempt" | "retry-attempt" }>;
}) {
  if (backing.kind === "verify-attempt") {
    return (
      <div className="ladder-detail">
        <h3>Verify round</h3>
        <dl className="meta">
          <div>
            <dt>Round</dt>
            <dd>#{backing.round}</dd>
          </div>
          <div>
            <dt>Verdict</dt>
            <dd className={backing.outcome === "pass" ? "verdict-pass" : "verdict-fail"}>
              {backing.outcome === "pass" ? "pass (advisory)" : "fail (advisory)"}
            </dd>
          </div>
          {backing.gateCommand ? (
            <div>
              <dt>Gate command</dt>
              <dd>
                <code>{backing.gateCommand}</code>
              </dd>
            </div>
          ) : null}
        </dl>
        <p className="muted">
          This round&apos;s gate ran on an overlay of the round&apos;s unit results
          and is advisory: it decides whether to retry. The final integration
          gate on the integrated tree decides the goal.
        </p>
        {backing.outcome === "fail" && backing.failingOutput ? (
          <>
            <h4>Failing gate output</h4>
            <pre className="detail-pre">{backing.failingOutput}</pre>
          </>
        ) : null}
        {backing.outcome === "fail" &&
        backing.implicatedUnits &&
        backing.implicatedUnits.length > 0 ? (
          <>
            <h4>
              Re-fanned units ({backing.implicatedUnits.length})
              {backing.refanSource ? ` via ${refanSourceLabel(backing.refanSource)}` : ""}
            </h4>
            <ul className="paths">
              {backing.implicatedUnits.map((u) => (
                <li key={u}>
                  <code>{u}</code>
                </li>
              ))}
            </ul>
            <p className="muted">
              This round's failure re-fanned these units on the next round. The
              re-fan source shows how they were chosen: {refanSourceExplainer}.
            </p>
          </>
        ) : null}
      </div>
    );
  }
  return (
    <div className="ladder-detail">
      <h3>Model escalation retry</h3>
      <dl className="meta">
        <div>
          <dt>Round</dt>
          <dd>#{backing.round}</dd>
        </div>
        <div>
          <dt>Model hop</dt>
          <dd>
            <code>{backing.fromModel || "base"}</code> {"->"}{" "}
            <code>{backing.toModel || "escalation model"}</code>
          </dd>
        </div>
      </dl>
      {backing.reason ? <p className="muted">{backing.reason}</p> : null}
      {backing.refanSource ? (
        <p className="muted">
          Re-fan source: <strong>{refanSourceLabel(backing.refanSource)}</strong>.
        </p>
      ) : null}
      <h4>Implicated units ({backing.implicatedUnits.length})</h4>
      {backing.implicatedUnits.length === 0 ? (
        <p className="muted">No specific unit was recorded for this retry.</p>
      ) : (
        <ul className="paths">
          {backing.implicatedUnits.map((u) => (
            <li key={u}>
              <code>{u}</code>
            </li>
          ))}
        </ul>
      )}
      <p className="muted">
        Re-ran the implicated units on a stronger model with the failing evidence.
      </p>
    </div>
  );
}

/**
 * The per-node activity log: the ordered REAL run steps the runner reported for
 * this unit (leased, cloning, calling model, applying edit, committing, pushing,
 * verified/failed). It renders the unit's recorded `activity` from state, so
 * every line corresponds to a real step the run emitted, not a UI-synthesized
 * one. An empty log means the run has not reported any step for this unit yet.
 */
function ActivityLog({ steps }: { steps: readonly ActivityStepSnapshot[] }) {
  return (
    <div className="activity-log">
      <h3>Activity log</h3>
      {steps.length === 0 ? (
        <p className="muted">No activity reported for this unit yet.</p>
      ) : (
        <ol className="activity-steps">
          {steps.map((step, i) => (
            <li key={`${step.at}-${i}`} className={`activity-step phase-${step.phase}`}>
              <span className="activity-phase">{step.phase}</span>
              <span className="activity-message">{step.message}</span>
            </li>
          ))}
        </ol>
      )}
    </div>
  );
}
