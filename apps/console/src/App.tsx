/**
 * Console for the Switchyard Change Fabric: the control plane.
 *
 * After `make dev-all`, a human does everything here in the browser. The console
 * shows a gallery of templates; selecting one launches a real live run with a
 * FRESH UNIQUE Change id (generated by the dev launcher that spawns the run) and
 * the console follows exactly that id. It then polls the Worker's live
 * orchestration state and projects each snapshot into the typed node/edge graph
 * with the shared `buildWorkGraphModel` (the exact same projection the tests
 * pin), and renders it. The morphing a watcher sees (nodes appearing as units
 * become runnable and agents are recruited, greening as evidence lands) is a
 * projection of real state transitions between successive snapshots, never a
 * timed animation.
 *
 * Honesty: because the view is `buildWorkGraphModel(state)` and every node in
 * that model carries a backing that resolves against the state (the builder
 * routes every node through `assertBacked`), it is impossible to show a node
 * with no backing state. Clicking a node reveals its real backing: for an agent
 * node, its real Artifact repo identity and its real status/evidence; for a
 * plain work node, the real WorkUnit it stands for.
 *
 * The escalating template genuinely PAUSES on a real pending escalation: the run
 * blocks until a human answers the question here, and the answer is this
 * console's POST straight to the Worker's resolve route, which ends the durable
 * wait and lets the graph advance. The non-escalating templates run to
 * completion with no human step.
 */

// The Worker control API runs separately under `wrangler dev`. Override with
// VITE_WORKER_URL when it is not on the default local port.
const WORKER_BASE: string =
  (import.meta.env.VITE_WORKER_URL as string | undefined) ?? "http://127.0.0.1:8787";
const POLL_MS = 1200;

/** The launcher-side status of a launched run (from GET /api/runs/:id). */
interface LaunchStatus {
  readonly status: "running" | "exited";
  readonly exitCode: number | null;
  readonly log: readonly string[];
}

/**
 * How a GET /changes/:id response should be treated at render time. Right after
 * a launch the run exists but has not POSTed the Change yet, so the Worker
 * answers 404; that is EXPECTED and must read as a quiet "pending" (keep polling,
 * surface no error) rather than a hard failure, so the first paint after a launch
 * does not flicker an alarming error. Once the Change has appeared at least once,
 * a later 404 is no longer the launch race and is handled as before (an error).
 * Any other non-ok status is a real error immediately. This is a pure decision so
 * it is unit-tested offline without a browser.
 */
export type ChangeFetchDisposition = "ok" | "pending" | "error";

export function classifyChangeResponse(
  status: number,
  ok: boolean,
  hasAppeared: boolean,
): ChangeFetchDisposition {
  if (ok) {
    return "ok";
  }
  // An early 404 (before the Change has ever appeared) is the launch race, not a
  // failure: treat it as pending and keep polling quietly.
  if (status === 404 && !hasAppeared) {
    return "pending";
  }
  return "error";
}

/** npm's own wrapper lines around a failed script (`npm error ...`, `npm ERR! ...`): never the run's reason. */
const NPM_BOILERPLATE = /^\s*npm (?:error|ERR!|warn|WARN)\b/;

/**
 * The run's OWN verdict and summary lines (as the CLI prints them), and any
 * error line: what a non-zero exit actually means.
 */
const RUN_SUMMARY_LINE =
  /^\s*(?:verdict:|items completed:|failure:|promoted(?: unverified \(no gate\))?:|not promoted:|partial:|not completed:|proposal rejected:|proposal undecided\b|\w*Error:)/;

/**
 * The lines worth showing when a launched run exits non-zero: the run's own
 * verdict and summary lines (`verdict:`, `items completed:`, `failure:`,
 * `promoted:`, the partial reasons, `Error:`), never npm's `npm error ...`
 * boilerplate. With no such line, the last few non-npm log lines (the last
 * `Error:` line pulled in first when it scrolled out of that tail). The log
 * is the launcher's already-redacted rolling CLI output; the raw log stays
 * one toggle away in the panel.
 */
export function runFailureLines(log: readonly string[], max = 12): string[] {
  const own = log.filter((line) => !NPM_BOILERPLATE.test(line));
  const summary = own.filter((line) => RUN_SUMMARY_LINE.test(line)).map((line) => line.trim());
  if (summary.length > 0) {
    return [...new Set(summary)].slice(-max);
  }
  const tail = own.slice(-max);
  const errorLine = [...own].reverse().find((line) => /\b\w*Error:/.test(line));
  if (errorLine === undefined || tail.includes(errorLine)) {
    return tail;
  }
  return [errorLine, ...tail.slice(-(max - 1))];
}

/**
 * The cost cell for a model transcript. A recorded positive USD is shown as is.
 * The gateway executor records `usd: 0` because no pricing table exists for
 * those models, so a zero (or missing) cost next to real token counts reads
 * "not metered" rather than a false $0. Null means there is nothing to show.
 */
export function formatCost(detail: {
  readonly usd?: number;
  readonly inputTokens?: number;
  readonly outputTokens?: number;
}): string | null {
  const tokens = (detail.inputTokens ?? 0) + (detail.outputTokens ?? 0);
  if (detail.usd !== undefined && detail.usd > 0) {
    return `$${detail.usd}`;
  }
  if (tokens > 0) {
    return "not metered";
  }
  return detail.usd !== undefined ? "0" : null;
}

/**
 * Whether a Change is a BOARD run: launched as one, or its snapshot reports a
 * board with messages (a run-live Change's board stays empty).
 */
export function isBoardRun(runMode: LaunchMode | null, snapshot: unknown): boolean {
  if (runMode === "board") {
    return true;
  }
  const board = (snapshot as { board?: { messages?: unknown } } | null)?.board;
  return typeof board?.messages === "number" && board.messages > 0;
}

export function App() {
  // No change-id box and no ?change= reliance: the console follows the UNIQUE id
  // the launcher hands back when a template is launched. Null means no run yet.
  const [changeId, setChangeId] = useState<string | null>(null);
  const [activeTemplate, setActiveTemplate] = useState<Template | null>(null);
  const [templates, setTemplates] = useState<readonly Template[]>(TEMPLATES);
  const [snapshot, setSnapshot] = useState<ChangeStateSnapshot | null>(null);
  const [error, setError] = useState<string | null>(null);
  // A quiet "waiting for the launched run to create the Change" flag. Right after
  // a launch the Worker answers 404 until the run POSTs the Change, which is the
  // launch race, not a failure. This flag shows a soft waiting line instead of
  // the generic empty state and clears on the first real snapshot.
  const [pending, setPending] = useState(false);
  // Whether the followed Change has appeared at least once. Once it has, a later
  // 404 is no longer the launch race and is handled as a real error.
  const hasAppearedRef = useRef(false);
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [min, setMin] = useState(1);
  const [max, setMax] = useState(3);
  const [busy, setBusy] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);
  const [launchStatus, setLaunchStatus] = useState<LaunchStatus | null>(null);
  // Per-app live deployment URLs from a MANUAL Deploy (app name -> workers.dev
  // URL). A deployment is created only by a human Deploy, surfaced persistently
  // here from the moment of deploy, through the run (which redeploys the fix in
  // place to the SAME URL), to teardown. This is the pre-run break the watcher
  // sees before launching a fix.
  const [deployedUrls, setDeployedUrls] = useState<Record<string, string>>({});
  // The template gallery collapses to a one-line strip while a run is active so
  // the graph sits near the top of the page.
  const [galleryOpen, setGalleryOpen] = useState(true);
  // The launch mode for the NEXT launch (run-live, or agents on the board) and,
  // for a board run, who answers contract decisions. The active run's mode is
  // kept separately so the view follows what was actually launched.
  const [launchMode, setLaunchMode] = useState<LaunchMode>("live");
  const [contractPolicy, setContractPolicy] = useState<ContractPolicy>("console");
  const [runMode, setRunMode] = useState<LaunchMode | null>(null);
  // The full board log of a board run, pulled incrementally (after the last seq).
  const [boardLog, setBoardLog] = useState<readonly BoardMessage[]>([]);
  const boardLogRef = useRef<readonly BoardMessage[]>([]);
  const boardPullInFlight = useRef(false);
  const [boardError, setBoardError] = useState<string | null>(null);

  // Restore the per-app deployments the launcher already knows about (its
  // .deployments markers), so a reload does not forget a prior manual Deploy.
  useEffect(() => {
    let cancelled = false;
    void fetch("/api/deployments")
      .then((res) => (res.ok ? res.json() : null))
      .then((body: { deployments?: Record<string, string> } | null) => {
        if (!cancelled && body?.deployments) {
          const known = body.deployments;
          setDeployedUrls((prev) => ({ ...known, ...prev }));
        }
      })
      .catch(() => {
        /* best-effort: no launcher means no restored deployments */
      });
    return () => {
      cancelled = true;
    };
  }, []);

  // Load the gallery from the launcher so the UI and the launcher share one
  // source of truth; fall back to the bundled descriptors when the launcher is
  // not reachable (for example a static preview build without the dev server).
  useEffect(() => {
    let cancelled = false;
    void fetch("/api/templates")
      .then((res) => (res.ok ? res.json() : null))
      .then((body: { templates?: Template[] } | null) => {
        if (!cancelled && body?.templates && body.templates.length > 0) {
          setTemplates(body.templates);
        }
      })
      .catch(() => {
        /* keep the bundled fallback */
      });
    return () => {
      cancelled = true;
    };
  }, []);

  const load = useCallback(async (id: string) => {
    try {
      const res = await fetch(`${WORKER_BASE}/changes/${encodeURIComponent(id)}`);
      const disposition = classifyChangeResponse(res.status, res.ok, hasAppearedRef.current);
      if (disposition === "pending") {
        // The launched run has not created the Change yet (an expected early
        // 404). Keep polling quietly: show a soft "waiting" state, surface no
        // error, and do not spam the console or clobber any prior snapshot.
        setError(null);
        setPending(true);
        return;
      }
      if (disposition === "error") {
        const body = (await res.json().catch(() => ({}))) as { error?: string };
        setError(body.error ?? `request failed (${res.status})`);
        setSnapshot(null);
        setPending(false);
        return;
      }
      hasAppearedRef.current = true;
      setSnapshot((await res.json()) as ChangeStateSnapshot);
      setError(null);
      setPending(false);
    } catch {
      setError(`cannot reach the Worker at ${WORKER_BASE}`);
      setSnapshot(null);
      setPending(false);
    }
  }, []);

  // Poll the Worker for the followed Change id. No run yet means nothing to poll.
  useEffect(() => {
    if (!changeId) {
      return;
    }
    void load(changeId);
    const timer = setInterval(() => void load(changeId), POLL_MS);
    return () => clearInterval(timer);
  }, [changeId, load]);

  // Poll the launcher for the run's process status, so the UI can show when the
  // run is still working, finished, or exited non-zero (an honest status, not a
  // guess from the graph alone).
  useEffect(() => {
    if (!changeId) {
      return;
    }
    let cancelled = false;
    const pull = () => {
      void fetch(`/api/runs/${encodeURIComponent(changeId)}`)
        .then((res) => (res.ok ? res.json() : null))
        .then((body: LaunchStatus | null) => {
          if (!cancelled && body) {
            setLaunchStatus(body);
          }
        })
        .catch(() => {
          /* launcher status is best-effort */
        });
    };
    pull();
    const timer = setInterval(pull, POLL_MS);
    return () => {
      cancelled = true;
      clearInterval(timer);
    };
  }, [changeId]);

  const boardMode = Boolean(changeId) && isBoardRun(runMode, snapshot);

  // Poll the board log for a board run: only what is new after the last seq,
  // paging while the Worker says there is more. The snapshot polling above
  // continues for the run's status and its pending escalations.
  useEffect(() => {
    if (!changeId || !boardMode) {
      return;
    }
    let cancelled = false;
    const pull = async () => {
      if (boardPullInFlight.current) {
        return;
      }
      boardPullInFlight.current = true;
      try {
        const result = await pullBoard(fetch, WORKER_BASE, changeId, boardLogRef.current);
        if (cancelled) {
          return;
        }
        if (result.log !== boardLogRef.current) {
          boardLogRef.current = result.log;
          setBoardLog(result.log);
        }
        setBoardError(result.status === "error" ? (result.error ?? "board request failed") : null);
      } finally {
        boardPullInFlight.current = false;
      }
    };
    void pull();
    const timer = setInterval(() => void pull(), POLL_MS);
    return () => {
      cancelled = true;
      clearInterval(timer);
    };
  }, [changeId, boardMode]);

  const resetBoard = useCallback(() => {
    boardLogRef.current = [];
    setBoardLog([]);
    setBoardError(null);
  }, []);

  // Build the graph model from the live snapshot. If the snapshot ever fails the
  // backing guard (an unbacked node), surface it loudly rather than drawing a
  // dishonest graph: the no-unbacked-node rule is enforced here too, at render.
  const { model, backingError } = useMemo((): {
    model: WorkGraphModel | null;
    backingError: string | null;
  } => {
    if (!snapshot) {
      return { model: null, backingError: null };
    }
    try {
      return { model: buildWorkGraphModel(snapshot), backingError: null };
    } catch (err) {
      return {
        model: null,
        backingError: err instanceof Error ? err.message : String(err),
      };
    }
  }, [snapshot]);

  // Keep the dial inputs in sync with the real dial the state reports, so the
  // control shows the config actually in force (not a local guess).
  const reportedDial = snapshot?.dial;
  const lastDialKey = useRef<string>("");
  useEffect(() => {
    if (!reportedDial) {
      return;
    }
    const key = `${reportedDial.minConcurrency}/${reportedDial.maxConcurrency}`;
    if (key !== lastDialKey.current) {
      lastDialKey.current = key;
      setMin(reportedDial.minConcurrency);
      setMax(reportedDial.maxConcurrency);
    }
  }, [reportedDial]);

  const selectedNode: GraphNode | null = useMemo(() => {
    if (!model || !selectedId) {
      return null;
    }
    return model.nodes.find((n) => n.id === selectedId) ?? null;
  }, [model, selectedId]);

  // Mutations go through the dev launcher's auth proxy when it has one (it adds
  // the Worker bearer server-side, so no secret is ever in this bundle), and
  // fall back to a direct Worker POST otherwise. See worker-post.ts.
  const post = useCallback(async (path: string, body?: unknown): Promise<boolean> => {
    try {
      const res = await postToWorker(fetch, WORKER_BASE, path, body);
      if (!res.ok) {
        const parsed = (await res.json().catch(() => ({}))) as { error?: string };
        setNotice(parsed.error ?? `request failed (${res.status})`);
        return false;
      }
      return true;
    } catch {
      setNotice(`cannot reach the Worker at ${WORKER_BASE}`);
      return false;
    }
  }, []);

  // The dial is set BEFORE a run and locked during it: there is no mid-run
  // re-POST that changes concurrency live. The chosen min/max is captured as the
  // launched run's config (passed through POST /api/launch), and while a run is
  // active the control is read-only, showing the in-force dial reported by state.

  // Launch a template: ask the launcher to start a real live run with a FRESH
  // UNIQUE Change id, then follow exactly that id. The browser is the launcher,
  // so there is no CLI step for the demo.
  const launchTemplate = useCallback(async (template: Template) => {
    setBusy(true);
    setNotice(null);
    try {
      const res = await fetch("/api/launch", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          templateId: template.id,
          min,
          max,
          ...(launchMode === "board" ? { mode: "board", decideContracts: contractPolicy } : {}),
        }),
      });
      if (!res.ok) {
        const parsed = (await res.json().catch(() => ({}))) as { error?: string };
        setNotice(parsed.error ?? `could not launch (${res.status})`);
        setBusy(false);
        return;
      }
      const body = (await res.json()) as { changeId: string; mode?: LaunchMode };
      // Follow the unique id the launcher generated. Reset the view for the run.
      setRunMode(body.mode ?? launchMode);
      resetBoard();
      setSnapshot(null);
      setSelectedId(null);
      setLaunchStatus(null);
      setError(null);
      // A fresh run: the Change has not appeared yet, so an early 404 reads as
      // the launch race (pending) until the run POSTs it.
      hasAppearedRef.current = false;
      setPending(true);
      setActiveTemplate(template);
      setChangeId(body.changeId);
      setGalleryOpen(false);
      setNotice(
        launchMode === "board"
          ? `launched ${template.name} with agents on the board as ${body.changeId}. ${
              contractPolicy === "console"
                ? "Contract decisions wait for your answer here."
                : `Contract decisions are answered automatically (${contractPolicy}).`
            }`
          : template.escalates
            ? `launched ${template.name} as ${body.changeId}. It will pause for your decision when it hits the shared path.`
            : `launched ${template.name} as ${body.changeId}. It runs to completion with no human step.`,
      );
    } catch {
      setNotice("cannot reach the launcher. Is `make dev-all` running?");
    }
    setBusy(false);
  }, [min, max, launchMode, contractPolicy, resetBoard]);

  // Manual Deploy (BEFORE a fix): deploy an app template's app in its CURRENT
  // (broken) state to its STABLE workers.dev URL, so the watcher sees the break
  // first. The URL is surfaced persistently and the fix later redeploys in place
  // to the SAME URL. This never launches a run; it is purely the deploy hop.
  const deployApp = useCallback(async (template: Template) => {
    if (!template.app) {
      return;
    }
    setBusy(true);
    setNotice(null);
    try {
      const res = await fetch("/api/deploy-app", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ templateId: template.id, app: template.app }),
      });
      const body = (await res.json().catch(() => ({}))) as { url?: string; error?: string };
      if (res.ok && body.url) {
        setDeployedUrls((prev) => ({ ...prev, [template.app as string]: body.url as string }));
        setNotice(
          `deployed ${template.name} in its current (broken) state to ${body.url}. ` +
            `Open it to see the break, then launch the fix to redeploy in place to the same URL.`,
        );
      } else {
        setNotice(body.error ?? `could not deploy ${template.name} (${res.status}).`);
      }
    } catch {
      setNotice("cannot reach the launcher to deploy. Is `make dev-all` running?");
    }
    setBusy(false);
  }, []);

  // Per-run cleanup: tear down THIS run's real Artifact repos (scoped to its
  // unique id), so clicking through templates repeatedly never leaves billable
  // repos. A new run uses a fresh unique id, so it never collides with a prior
  // run even before cleanup.
  const cleanupRun = useCallback(async () => {
    if (!changeId) {
      return;
    }
    setBusy(true);
    try {
      const teardownApp = activeTemplate?.app;
      const res = await fetch("/api/cleanup", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ changeId, ...(teardownApp ? { app: teardownApp } : {}) }),
      });
      const body = (await res.json().catch(() => ({}))) as {
        ok?: boolean;
        output?: string[];
        error?: string;
      };
      if (res.ok && body.ok) {
        setNotice(`torn down the real repos for ${changeId}.`);
        setSnapshot(null);
        setSelectedId(null);
        setChangeId(null);
        setActiveTemplate(null);
        setLaunchStatus(null);
        setRunMode(null);
        resetBoard();
        setGalleryOpen(true);
        if (teardownApp) {
          setDeployedUrls((prev) => {
            const next = { ...prev };
            delete next[teardownApp];
            return next;
          });
        }
      } else {
        setNotice(body.error ?? `cleanup did not complete for ${changeId}.`);
      }
    } catch {
      setNotice("cannot reach the launcher to clean up. Is `make dev-all` running?");
    }
    setBusy(false);
  }, [changeId, activeTemplate, resetBoard]);

  // Answer a board escalation (a contest or a protected contract) through the
  // existing resolve route, proxied by the launcher when it can.
  const resolveBoardEscalation = useCallback(
    async (id: string, decision: string) => {
      if (!changeId) {
        return;
      }
      setBusy(true);
      try {
        const res = await resolveEscalation(fetch, WORKER_BASE, changeId, id, decision);
        if (res.ok) {
          setNotice(`escalation ${id} resolved: ${decision}. The board continues.`);
          await load(changeId);
        } else {
          const parsed = (await res.json().catch(() => ({}))) as { error?: string };
          setNotice(parsed.error ?? `request failed (${res.status})`);
        }
      } catch {
        setNotice(`cannot reach the Worker at ${WORKER_BASE}`);
      }
      setBusy(false);
    },
    [changeId, load],
  );

  return (
    <main className={`app-shell${boardMode ? " is-wide" : ""}`}>
      <header className="app-header">
        <h1>Switchyard Change Fabric</h1>
        <p className="tagline">A living work graph, every node backed by real state</p>
      </header>

      <TemplateGallery
        templates={templates}
        activeId={activeTemplate?.id ?? null}
        busy={busy}
        deployedUrls={deployedUrls}
        collapsed={Boolean(changeId) && !galleryOpen}
        onToggle={() => setGalleryOpen((open) => !open)}
        onLaunch={launchTemplate}
        onDeploy={deployApp}
        launchMode={launchMode}
      >
        <DialControl
          min={min}
          max={max}
          locked={Boolean(changeId)}
          onMin={setMin}
          onMax={setMax}
        />
        <RunModeControl
          mode={launchMode}
          policy={contractPolicy}
          locked={Boolean(changeId)}
          onMode={setLaunchMode}
          onPolicy={setContractPolicy}
        />
      </TemplateGallery>

      <section className="app-panel" aria-label="Run status">
        {changeId ? (
          <RunStatus
            changeId={changeId}
            template={activeTemplate}
            launchStatus={launchStatus}
            liveUrl={
              snapshot?.deployment?.url ??
              (activeTemplate?.app ? deployedUrls[activeTemplate.app] : undefined)
            }
            redeployed={Boolean(snapshot?.deployment?.url)}
            dial={
              reportedDial
                ? { min: reportedDial.minConcurrency, max: reportedDial.maxConcurrency }
                : { min, max }
            }
            busy={busy}
            onTearDown={() => void cleanupRun()}
          />
        ) : (
          <p className="muted">Pick a template above to launch a live run.</p>
        )}
        {error ? <p className="error">{error}</p> : null}
        {pending && !snapshot && !error ? (
          <p className="muted">Waiting for the launched run to create the change...</p>
        ) : null}
        {notice ? <p className="notice">{notice}</p> : null}
      </section>

      {backingError ? (
        <section className="app-panel" aria-label="Honesty guard">
          <p className="error">
            Refusing to render: a node had no backing state ({backingError}). The graph
            only draws nodes that map to real ChangeState.
          </p>
        </section>
      ) : null}

      {snapshot?.planningFailure ? (
        <section className="app-panel" aria-label="Planning failed">
          <p className="detail-warning" role="alert">
            <strong>Planning failed:</strong> {snapshot.planningFailure.reason}
          </p>
        </section>
      ) : null}

      {boardMode ? (
        <>
          {boardError ? <p className="error">{boardError}</p> : null}
          {boardLog.length > 0 ? (
            <MissionControl
              log={boardLog}
              escalations={(snapshot?.escalations ?? []) as readonly BoardEscalationRecord[]}
              busy={busy}
              onResolve={resolveBoardEscalation}
            />
          ) : (
            <section className="app-panel">
              <p className="muted">Waiting for the board: the goal has not been posted yet.</p>
            </section>
          )}
        </>
      ) : null}

      {!boardMode && snapshot && changeId && (snapshot.escalations?.length ?? 0) > 0 ? (
        <EscalationPanel
          escalations={snapshot.escalations ?? []}
          busy={busy}
          onResolve={async (id, decision) => {
            setBusy(true);
            const ok = await post(
              `/changes/${encodeURIComponent(changeId)}/escalations/${encodeURIComponent(id)}/resolve`,
              { decision },
            );
            if (ok) {
              setNotice(`escalation ${id} resolved: ${decision}. The run continues.`);
              await load(changeId);
            }
            setBusy(false);
          }}
        />
      ) : null}

      {!boardMode && model ? (
        <section className="app-panel graph-panel" aria-label="Living work graph">
          <GraphView model={model} selectedId={selectedId} onSelect={setSelectedId} />
          <Legend />
        </section>
      ) : null}

      {!boardMode && selectedNode ? (
        <NodeDetail
          node={selectedNode}
          changePassed={model ? changeHasPassed(model) : false}
          onClose={() => setSelectedId(null)}
        />
      ) : null}
    </main>
  );
}

