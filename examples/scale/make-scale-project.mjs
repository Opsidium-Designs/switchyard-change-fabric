#!/usr/bin/env node
/**
 * make-scale-project: write a ~100-module TypeScript project into a directory,
 * deterministically, for the SIMULATED 100-agent board run (make
 * demo-board-scale). It is generated at run time so the repo does not carry
 * 100 example files.
 *
 *   node examples/scale/make-scale-project.mjs <dir> [--domains N] [--modules N]
 *
 * Shape: N domains (default 10) of M route modules (default 10), one file each
 * under src/<domain>/<module>.ts, over three shared seam files every module
 * imports (src/contracts/money.ts, validate.ts, http.ts), plus src/index.ts.
 * A few modules import a sibling (the last module of each domain imports the
 * first), so the plan has some dependency order, not one flat wave.
 *
 * The project has no dependencies and no `gate` script: the offline run's gate
 * FIXTURE stands in for a gate, and the run is labelled as such. Writing is
 * deterministic: the same arguments always produce byte-identical files. The
 * directory must be empty or absent.
 */

import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const DOMAINS = ["parking", "permits", "transit", "parks", "housing", "records", "licensing", "utilities", "library", "health", "schools", "waste"];
const MODULES = ["applications", "fees", "renewals", "appeals", "citations", "refunds", "waitlists", "reports", "notices", "schedules", "audits", "exports"];

function parseArgs(argv) {
  const out = { dir: undefined, domains: 10, modules: 10 };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--domains" || arg === "--modules") {
      const value = Number(argv[i + 1]);
      const max = arg === "--domains" ? DOMAINS.length : MODULES.length;
      if (!Number.isInteger(value) || value < 1 || value > max) {
        throw new Error(`${arg} must be an integer from 1 to ${max}`);
      }
      out[arg.slice(2)] = value;
      i += 1;
    } else if (out.dir === undefined && !arg.startsWith("--")) {
      out.dir = arg;
    } else {
      throw new Error(`unexpected argument: ${arg}`);
    }
  }
  if (out.dir === undefined) {
    throw new Error("usage: make-scale-project.mjs <dir> [--domains N] [--modules N]");
  }
  return out;
}

function write(root, path, text) {
  const full = join(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, text);
}

const MONEY = `// Shared money contract: amounts are integer cents.
export type Cents = number;

export function cents(amount: number): Cents {
  return Math.round(amount * 100);
}

export function addCents(a: Cents, b: Cents): Cents {
  return a + b;
}
`;

const VALIDATE = `// Shared validation contract.
export function text(value: unknown): string {
  return String(value);
}

export function count(value: unknown): number {
  return Number(value);
}
`;

const HTTP = `// Shared http contract.
export interface Reply {
  readonly status: number;
  readonly body: unknown;
}

export function ok(body: unknown): Reply {
  return { status: 200, body };
}
`;

function moduleSource(domain, module, sibling) {
  const name = `${domain}${module[0].toUpperCase()}${module.slice(1)}`;
  const siblingImport = sibling ? `import { ${sibling.name}Total } from "./${sibling.module}.ts";\n` : "";
  const siblingUse = sibling ? ` + ${sibling.name}Total([])` : "";
  return `// ${domain} ${module}: one route module. It trusts its input today.
import { addCents, cents, type Cents } from "../contracts/money.ts";
import { count, text } from "../contracts/validate.ts";
import { ok, type Reply } from "../contracts/http.ts";
${siblingImport}
export function ${name}Total(amounts: readonly number[]): Cents {
  return amounts.reduce<Cents>((sum, a) => addCents(sum, cents(a)), 0)${siblingUse};
}

export function ${name}Handle(input: Record<string, unknown>): Reply {
  const label = text(input.label);
  const n = count(input.n);
  return ok({ module: "${domain}/${module}", label, n, total: ${name}Total([n]) });
}
`;
}

function main() {
  const { dir, domains, modules } = parseArgs(process.argv.slice(2));
  const root = resolve(dir);
  if (existsSync(root) && readdirSync(root).length > 0) {
    throw new Error(`${root} is not empty`);
  }
  mkdirSync(root, { recursive: true });
  const usedDomains = DOMAINS.slice(0, domains);
  const usedModules = MODULES.slice(0, modules);

  write(
    root,
    "package.json",
    `${JSON.stringify(
      {
        name: "scale-project",
        version: "0.0.0",
        private: true,
        description: "A generated ~100-module project for the simulated board run at scale.",
        license: "Apache-2.0",
        type: "module",
        scripts: {},
      },
      null,
      2,
    )}\n`,
  );
  write(
    root,
    "README.md",
    `# scale-project\n\nGenerated by examples/scale/make-scale-project.mjs: ${domains} domains x ${modules} route modules over three shared contracts (money, validate, http). No dependencies and no gate of its own.\n`,
  );
  write(root, "src/contracts/money.ts", MONEY);
  write(root, "src/contracts/validate.ts", VALIDATE);
  write(root, "src/contracts/http.ts", HTTP);

  const index = [];
  for (const domain of usedDomains) {
    usedModules.forEach((module, m) => {
      // The last module of each domain reads the first one's totals: a dependency.
      const first = usedModules[0];
      const sibling =
        modules > 1 && m === modules - 1
          ? { module: first, name: `${domain}${first[0].toUpperCase()}${first.slice(1)}` }
          : undefined;
      write(root, `src/${domain}/${module}.ts`, moduleSource(domain, module, sibling));
      index.push(`export * from "./${domain}/${module}.ts";`);
    });
  }
  write(root, "src/index.ts", `// Every route module, re-exported.\n${index.join("\n")}\n`);
  console.log(`wrote ${domains * modules} modules in ${domains} domains under ${root}`);
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
